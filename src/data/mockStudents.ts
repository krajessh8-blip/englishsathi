const STORAGE_KEY = 'smart_english_sathi_students_data_v3';
const LEGACY_STORAGE_KEY_V2 = 'smart_english_sathi_students_data_v2';
const LEGACY_STORAGE_KEY_V1 = 'smart_english_sathi_students_data';
const LEGACY_STORAGE_KEY_ORIGINAL = 'mvm_kenedi_students_data';

export function getStoredStudents(): Student[] {
  if (typeof window === 'undefined') return INITIAL_STUDENTS;
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      return JSON.parse(saved);
    }

    // Check older versions and migrate or seed INITIAL_STUDENTS
    const olderSaved =
      localStorage.getItem(LEGACY_STORAGE_KEY_V2) ||
      localStorage.getItem(LEGACY_STORAGE_KEY_V1) ||
      localStorage.getItem(LEGACY_STORAGE_KEY_ORIGINAL);

    if (!olderSaved) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_STUDENTS));
      return INITIAL_STUDENTS;
    }

    // Migrate older saved data and merge with INITIAL_STUDENTS to ensure all 10 levels are populated
    const parsed: Student[] = JSON.parse(olderSaved);
    const existingIds = new Set(parsed.map((s) => s.id));
    const migrated: Student[] = parsed.map((st) => {
      const levelId = st.levelId || mapGroupToLevel(st.groupId, st.grade);
      return {
        ...st,
        levelId,
        groupId: st.groupId || mapLevelToGroup(levelId),
      };
    });

    // Add any missing level students from INITIAL_STUDENTS so all 10 levels have representation
    for (const initStudent of INITIAL_STUDENTS) {
      if (!existingIds.has(initStudent.id)) {
        migrated.push(initStudent);
      }
    }

    localStorage.setItem(STORAGE_KEY, JSON.stringify(migrated));
    return migrated;
  } catch {
    return INITIAL_STUDENTS;
  }
}

export function saveStudents(students: Student[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(students));
  } catch (err) {
    console.error('Failed to save students to localStorage', err);
  }
}
